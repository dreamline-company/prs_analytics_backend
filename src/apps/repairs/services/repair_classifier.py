"""Разделение ремонтов на «ремонт оборудования» и ГТМ.

ГТМ — геолого-технические мероприятия: промывка/очистка забоя (механические
примеси), подготовка к ГИС и ГРП, ГРП, ликвидация скважин, консервация,
расконсервация и ввод из консервации, ввод из бурения (освоение) — перечень
подтверждён геологом заказчика. Аварийными ремонтами оборудования они не
считаются: заказчик исключает их из ЧРФ и считает отдельно «МРП без ГТМ».
Смена способа эксплуатации (ЭВН ↔ ШГН) — обычный учитываемый ремонт, не ГТМ.

Признак берётся из вида работ (``repairs_repair_type.name_ru``); текст работ
используется только когда вид ремонта неизвестен. Проверено по отчёту заказчика
(Кайнармунайгаз, скользящий год до 08.2026): ГТМ 204 против 207.
Признака «по технической причине» из ABAI в данных нет — он не определяется.
"""

import re
from typing import Final

# ABAI repair_work_type 3012 — «По мероприятию»: у заказчика «Подготовка к ГИС и
# ГРП». Нужен только когда название вида не загружено.
GTM_REPAIR_TYPE_ID: Final = 3012
# То же для видов, названия которых не загружены: TP 9-1 (подготовка к ГТМ, ГРП),
# TP 9-2 (подготовка к ГИС), TP 8-7 (промывка забоя), КР-12 (ликвидация скважин).
GTM_REPAIR_TYPE_IDS: Final = frozenset({GTM_REPAIR_TYPE_ID, 3009, 3025, 3041})

_GTM_TYPE_NAME = re.compile(
    r"мероприят|меропр|геолого-технич"
    # промывка / очистка забоя (мех. примеси); не промывка насоса, клапанов, линий
    r"|подготовк\w*[^;]{0,30}гис|грп|гидроразрыв"
    r"|консерв"
    r"|ликвидац\w*\s+(?:водозаборной\s+)?скважин|переликвидац|физическая ликвидация"
    r"|освоени|ввод\w*[^;]{0,40}бурени|после бурени",
    re.IGNORECASE,
)
_GTM_FLUSH_TYPE_NAME = re.compile(r"промывк|очистк\w*\s+забо", re.IGNORECASE)
_NOT_FLUSH_OF_WELL = re.compile(
    r"насос|клапан|выкидн|водозабор|нагнетател",
    re.IGNORECASE,
)
_GTM_TEXT = re.compile(
    r"по мероприят|по меропр|консервац|гидроразрыв"
    # «гтм», «пвр» (прострелочно-взрывные работы) и «подготовка к ГИС» —
    # явные признаки ГТМ, встречаются в ремонтах Жылыоймунайгаза
    r"|\b(?:грп|гтм|пвр)\b|подготовк\w* к (?:проведению )?гис"
    r"|перфорац|дострел|кислотн",
    re.IGNORECASE,
)
_FAILURE_TEXT = re.compile(
    r"обрыв|отворот|слом|заклин|расхаж"
    r"|смен\w* (?:насос|нкт|штанг|полир)"
    r"|замен\w* (?:насос|нкт|штанг|полир|привод|винтов|ксг)"
    r"|винтов\w* пар|негодн|ревизи|утечк|пропуск|износ|срез",
    re.IGNORECASE,
)
# «пром-305-334м» — промывка забоя с реальным интервалом; пустое «пром-м» — шаблон.
_FLUSH_WITH_INTERVAL = re.compile(r"пром-\s*\d", re.IGNORECASE)


def is_gtm_repair(
    *,
    repair_type_id: int | None,
    repair_type_name: str | None,
    work_list: str | None,
) -> bool:
    """True, если ремонт — ГТМ, а не ремонт оборудования."""
    if repair_type_name:
        # Вид работ известен — решает он (перечень ГТМ подтверждён геологом);
        # текст ремонта — только запасной вариант, когда вида нет.
        if _GTM_TYPE_NAME.search(repair_type_name):
            return True
        return bool(
            _GTM_FLUSH_TYPE_NAME.search(repair_type_name)
            and not _NOT_FLUSH_OF_WELL.search(repair_type_name),
        )
    if repair_type_id in GTM_REPAIR_TYPE_IDS:
        return True

    text = work_list or ""
    if _GTM_TEXT.search(text):
        return True
    # Явная неисправность оборудования важнее промывки: «обрыв штанги … пром-…»
    # — это отказ, а не ГТМ.
    if _FAILURE_TEXT.search(text):
        return False
    return bool(_FLUSH_WITH_INTERVAL.search(text))


# «По технической причине» (форма МРП заказчика): замена верхнего (устьевого)
# оборудования и замена штока. Это ремонт, но в отказы для «МРП без ГТМ» он не
# входит; в ЧРФ такие ремонты учитываются (методика ЧРФ: «прочие» — да).
_TECH_TYPE_NAME = re.compile(
    r"(?:замен|смен)\w*\s+(?:полированн\w*\s+)?штока"
    r"|устьев\w*\s+оборудован|сусг|сальник",
    re.IGNORECASE,
)
_TECH_TEXT = re.compile(
    r"замен\w*\s+(?:полир\w*\s+)?шток|(?:смен|замен|ревизи)\w*\s+устьев",
    re.IGNORECASE,
)


def is_technical_repair(
    *,
    repair_type_id: int | None,
    repair_type_name: str | None,
    work_list: str | None,
) -> bool:
    """True, если ремонт «по технической причине»: не ГТМ, замена устья или штока."""
    if is_gtm_repair(
        repair_type_id=repair_type_id,
        repair_type_name=repair_type_name,
        work_list=work_list,
    ):
        return False
    if repair_type_name:
        return bool(_TECH_TYPE_NAME.search(repair_type_name))
    return bool(_TECH_TEXT.search(work_list or ""))
