"""Разделение ремонтов на «ремонт оборудования» и ГТМ.

ГТМ — геолого-технические мероприятия (подготовка к ГИС/ГРП, ввод из
консервации, перфорация, промывка забоя от мех. примесей): аварийными
ремонтами оборудования не считаются. Заказчик исключает их из ЧРФ и считает
отдельно «МРП без ГТМ».

Признак берётся из вида работ (``repairs_repair_type.name_ru``), а когда вид
ничего не говорит — из текста работ. Правила откалиброваны на ручной разметке
заказчика (Кайнармунайгаз, 01.06.2025–31.05.2026, 480 ремонтов): на скважинах
с совпавшим числом ремонтов деление ГТМ/не ГТМ совпадает примерно в 80% случаев.
Признака «по технической причине» из ABAI в данных нет — он не определяется.
"""

import re
from typing import Final

# ABAI repair_work_type 3012 — «По мероприятию»: у заказчика «Подготовка к ГИС и
# ГРП». Нужен только когда название вида не загружено.
GTM_REPAIR_TYPE_ID: Final = 3012

_GTM_TYPE_NAME = re.compile(r"мероприят|меропр", re.IGNORECASE)
_GTM_TEXT = re.compile(
    r"по мероприят|по меропр|консервац|гидроразрыв"
    # «гтм», «пвр» (прострелочно-взрывные работы) и «подготовка к ГИС» —
    # явные признаки ГТМ, встречаются в ремонтах Жылыоймунайгаза
    r"|\b(?:грп|гтм|пвр)\b|подготовк\w* к (?:проведению )?гис"
    r"|перфорац|дострел|кислотн",
    re.IGNORECASE,
)
_FAILURE_TEXT = re.compile(
    r"обрыв|отворот|слом|заклин|расхаж"
    r"|смен\w* (?:насос|нкт|штанг|полир)"
    r"|замен\w* (?:насос|нкт|штанг|полир|привод|винтов|ксг)"
    r"|винтов\w* пар|негодн|ревизи|утечк|пропуск|износ|срез",
    re.IGNORECASE,
)
# «пром-305-334м» — промывка забоя с реальным интервалом; пустое «пром-м» — шаблон.
_FLUSH_WITH_INTERVAL = re.compile(r"пром-\s*\d", re.IGNORECASE)


def is_gtm_repair(
    *,
    repair_type_id: int | None,
    repair_type_name: str | None,
    work_list: str | None,
) -> bool:
    """True, если ремонт — ГТМ, а не ремонт оборудования."""
    if repair_type_name and _GTM_TYPE_NAME.search(repair_type_name):
        return True
    if repair_type_id == GTM_REPAIR_TYPE_ID:
        return True

    text = work_list or ""
    if _GTM_TEXT.search(text):
        return True
    # Явная неисправность оборудования важнее промывки: «обрыв штанги … пром-…»
    # — это отказ, а не ГТМ.
    if _FAILURE_TEXT.search(text):
        return False
    return bool(_FLUSH_WITH_INTERVAL.search(text))
