from datetime import timedelta

# Сигнал относится к отказу, если эпизод открылся не раньше стольких суток до
# поломки (без поломки — до начала ремонта). 7 суток теряли 4 отказа из 47,
# 30 суток добавляли только 2.
SIGNAL_LOOKBACK = timedelta(days=14)

# Соседние статусы ABAI — одна цепочка простоя, если между ними не больше
# этого. В ABAI статусы идут встык: 1 мин и 24 ч дали одно и то же.
CHAIN_GAP = timedelta(hours=1)

# Глубже этого от начала ремонта поломку не ищем (на проде максимум — 41 сут).
CHAIN_MAX_DEPTH = timedelta(days=60)

# Простой, начавшийся не раньше чем за столько до начала ремонта, — сам ремонт,
# а не отдельная поломка (ABAI округляет время до минуты).
SAME_MOMENT = timedelta(hours=1)

# Запас выборки статусов и ремонтов до начала периода: поломка ищется до
# CHAIN_MAX_DEPTH назад от ремонта, окно сигнала — ещё SIGNAL_LOOKBACK.
HISTORY_DEPTH = CHAIN_MAX_DEPTH + SIGNAL_LOOKBACK

# Тип ремонта ABAI (well_workover.repair_type). Набор ремонтов — как в МРП:
# по типу не отсекаем, только ГТМ.
REPAIR_KIND_BY_ABAI_TYPE = {
    1: "КРС",
    2: "ТРС",
    3: "ПРС",
    4: "Прочие простои",
    5: "Наземный ремонт",
}
