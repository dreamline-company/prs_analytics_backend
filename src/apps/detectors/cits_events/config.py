# Сколько последних суток смотреть для «замер устарел» и для сверки «простой
# в ABAI, а СУ работает». Автор брал три суток до даты фиксации, потому что
# фиксировал на сегодня (сутки неполные); у нас дата фиксации — закрытые
# сутки, поэтому она сама входит в окно.
SU_RECENT_D = 3

# --- Статусы ABAI (мнемокоды well_status_type) ---
STATUS_WORK = "WRK"
