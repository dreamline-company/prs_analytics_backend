"""Пороги и параметры правила R10 — события по замерам ЦИТС относительно техрежима.

Значения перенесены из скрипта автора правила ``cits_events.py`` (версия
2026-09-18.5) без подгонки. Автор считает их предварительными: ретро-проверка
не проведена, и менять их отдельно от неё не нужно.

Отличия от скрипта — решения владельца от 28.09.2026:

- у скважин в периодической эксплуатации замер устаревает через
  ``STALE_D_PERIODIC`` суток, а не через ``STALE_D``: их замеряют реже, и при
  общем пороге они занимали половину раздела «запросить замер»;
- «замер устарел» делится по признаку работы СУ, как нулевые замеры:
  на проде почти все такие скважины стоят без статуса простоя, и действие
  по ним — не замер, а разбор, почему скважина стоит.
"""

