"""Пороги эпизодной логики R2 (стадии / нормализация).

Отдельно от ``config.py``: тот описывает само правило аварии (алармный порог,
корзины, сустейн) и не меняется, здесь — надстройка жизненного цикла эпизода.

С 19.11.2026 (правило заказчика) у эпизода две стадии:

- ``warning`` — «Падение нагрузки»: первые часы после провала момента;
- ``alarm`` — «Возможный обрыв штанг»: момент не вернулся за 4 часа от начала
  провала (T0 = ``opened_at``).

Порог 40 % (``config.MOM_DROP_RATIO``) по-прежнему открывает эпизод, но сам
больше не эскалирует. Подтверждает обрыв только ПРС — это проверка
(``verification``), не state machine. Разбор и цифры прода —
``docs/r2_interpretation_plan.md``.
"""

from apps.detectors.models.incident import (
    INCIDENT_LEVEL_ALARM,
    INCIDENT_LEVEL_WARNING,
)

# --- Сигналы правила (reason_code эпизодов) ---
REASON_ROD_BREAK = "rod_break"

# --- Открытие: деградация момента ---
# Момент ниже этой доли медианы-24ч (аларм — MOM_DROP_RATIO=0.4 из config.py)
# при живой скорости (тот же SPD_KEEP_RATIO).
WARN_MOM_DROP_RATIO = 0.6
# Сколько подряд корзин держится мягкий флаг: 4 x 15мин = 1 час.
WARN_SUSTAIN_BUCKETS = 4

# --- Стадии ---
STAGE_LABELS_RU = {
    INCIDENT_LEVEL_WARNING: "Падение нагрузки",
    INCIDENT_LEVEL_ALARM: "Возможный обрыв штанг",
}
# Через столько часов от T0 «Падение нагрузки» становится «Возможный обрыв
# штанг», если момент не вернулся.
STAGE_ESCALATE_HOURS = 4
# «Вернулся» = средний момент за последний час (T0 + 3…4 ч, дальше — час до
# текущей корзины) не ниже этой доли базы. На проде (165 эпизодов авг–ноя
# 2026) у 38 обрывов максимум 67 %, у ложных по моменту 35 из 37 ≥ 75 %.
STAGE_CHECK_WINDOW_HOURS = 1
STAGE_RECOVER_RATIO = 0.75
# Час проверки неполный (перерыв связи) — решение откладывается до полного
# часа данных: нужно столько 15-минутных корзин с отсчётами и столько
# отсчётов. На проде станции пишут ~12–13 отсчётов в час (медиана 13, у 2 %
# часов меньше 10), поэтому порог по отсчётам низкий, а неполноту часа ловят
# корзины: после перерыва первая корзина — одна из четырёх.
STAGE_WINDOW_MIN_BUCKETS = 3
STAGE_WINDOW_MIN_SAMPLES = 8

# --- База эпизода (замороженная) ---
# Средний момент за сутки до T0 по отсчётам, где ротор крутился (скорость >
# FAILURE_SPD_ABS). Считается один раз при открытии и до конца эпизода не
# меняется: плавающая медиана после обрыва сползала к аварийному уровню и
# закрывала настоящие обрывы через 12–13 ч (16 из 38 на проде; с замороженной — 2).
BASE_HOURS = 24
# Слабая скважина: и порог R2 ненадёжен (MIN_BASE_MOMENT в config.py), и по
# доле от базы стадию не решаем — доказать возврат нечем, эскалация.
BASE_MIN = 50.0
BASE_MIN_SAMPLES = 60

# --- Нормализация (гистерезис закрытия) ---
# Восстановление: медиана момента корзины выше этой доли базы И скорость выше
# FAILURE_SPD_ABS. Медиана, а не MIN: MIN нужен, чтобы поймать провал, а у
# пульсирующих скважин он и в норме ниже 75 % среднего.
RECOVER_RATIO = 0.75
# Сколько подряд корзин держится восстановление: 12 x 15мин = 3 часа.
RECOVER_SUSTAIN_BUCKETS = 12

# --- Закрытие без восстановления ---
# Нет ни восстановления, ни ремонта столько суток от T0 — эпизод закрывается
# как stale (как у R9): иначе простой «Нет подачи» без ремонта или скважина,
# ушедшая на новый уровень момента, висят «Возможным обрывом» вечно.
STALE_DAYS = 14

# Ремонт без даты окончания (не закрыт в ABAI) считается идущим не дольше
# стольких суток: во время ремонта эпизоды не открываются, а у висящих в ABAI
# ремонтов без конца это глушило бы R2 навсегда.
REPAIR_OPEN_MAX_DAYS = 7

# Сколько корзин-улик класть в payload вокруг события.
EVIDENCE_BUCKETS = 8
