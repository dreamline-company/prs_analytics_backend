"""Пороги и окна проверки эпизодов R2 независимыми данными.

Все окна отсчитываются от T0 — ``opened_at`` эпизода (начало провала момента,
местное время). Значения подобраны на 61 событии R2 (авг–окт 2026) и 117
исторических обрывах с 15.01.2026, см. docs/r2_verification.md; правило v3 —
на 165 эпизодах авг–ноя 2026, docs/r2_interpretation_plan.md.
"""

# Версия набора порогов — пишется в каждую отметку.
# v2 — ложная по восстановлению момента (19.10.2026).
# v3 — «Подтверждено» только ПРС с обрывом штанг, остальное «Не подтверждено»
#      (правило заказчика, 19.11.2026).
RULE_VERSION = "r2-verify-v3"

# --- Подтверждение ремонтом (v3) ---
# Сколько суток ждём ПРС с обрывом: медиана на проде 43 ч, но бывает 21 и
# 31 сут (VMB_2051, VMB_2017). Пока окно открыто — «Ожидает подтверждения».
PRS_WAIT_DAYS = 45
# Ремонт, идущий на момент T0, ищем не глубже: в ABAI бывают незакрытые
# ремонты многомесячной давности, а ПРС длится дни.
COVER_LOOKBACK_DAYS = 14
# Работы ремонта в ABAI дописывают после начала: решение «ремонт другого
# вида» ждёт закрытия ремонта плюс столько суток.
REPAIR_TEXT_GRACE_DAYS = 2
# Категория ремонта ABAI well_repair_type: 3 — ПРС. У ремонта без категории
# ПРС узнаём по виду работ «TP …».
ABAI_REPAIR_TYPE_PRS = 3
PRS_WORK_TYPE_PREFIX = "tp "
# Обрыв штанг в тексте работ: событие, а следом (≤ ROD_BREAK_GAP символов,
# до «.» или «;») — часть штанговой колонны. Опечатки «штаги», «61-штанги»
# встречаются; НКТ, кабель, ротор, плунжер между ними — не штанги.
ROD_BREAK_EVENTS = r"обрыв|отворот|слом|излом|срыв\s+резьб"
ROD_BREAK_PARTS = r"штанг|штаг|шток|центратор"
ROD_BREAK_NOT_PARTS = r"нкт|кабел|ротор|плунжер"
ROD_BREAK_GAP = 40
# Вид работ, означающий обрыв штанг, — запасной признак, когда текста нет.
ROD_BREAK_WORK_TYPE = "устранение обрыва штанг"

# --- Окна, часы от T0 ---
# Сколько ждём годный замер нефти; позже — «не удалось проверить».
WINDOW_HOURS = 96
# Замеры раньше этого не считаем: описывают время до отказа.
MEASUREMENT_MIN_DELAY_HOURS = 4
# Сколько привод должен проработать после годного замера.
DRIVE_AFTER_MEASUREMENT_HOURS = 12
# Статусы ABAI берём от T0 − ABAI_LOOKBACK_HOURS до T0 + ABAI_WINDOW_DAYS:
# простой после тревоги закрывает окно замера нефти и идёт в доказательства.
ABAI_LOOKBACK_HOURS = 12
ABAI_WINDOW_DAYS = 7

# --- Привод (регистр СДМО 1999 «Статус») ---
# Коды работы привода: при них двигатель под нагрузкой в 99,7–99,99 % отсчётов.
# Остальные коды (0, 512, 4096, 16384, 1048576 …) — остановка или авария.
DRIVE_WORK_CODES = frozenset({1, 2, 4})
# Доля отсчётов «работает», начиная с которой привод считается работавшим.
DRIVE_WORK_SHARE_MIN = 0.9
# Часов полной остановки (все отсчёты часа — не работа) для «скорее всего
# поломка»: ≈ 10 % окна, то есть доля работы за окно уже не наберёт 90 %.
DRIVE_STOPPED_HOURS_LIKELY = 10

# --- Момент штанги (регистр СДМО 1991, скорость ротора — 1998) ---
# Ложная тревога, если средний момент в окне T0+1…6 ч не ниже 75 % среднего
# момента за 24 ч до T0 (там — только отсчёты, где ротор крутился). При обрыве
# вал крутится без нагрузки и момент не возвращается. Подобрано перебором на
# 103 эпизодах прода 19.10.2026: ложных 24 из 27, поломок (обрыв по ремонту,
# иной ремонт, привод стоял) 0 из 34 — максимум у них 53 %; порог 70–75 % —
# плато, 75 % даёт больший запас. Окно 1–3 ч не годится: у обрыва VMB_0406
# момент первые 3 ч держался на 75 %; 12 ч почти ничего не добавляет.
MOMENT_BASE_HOURS = 24
MOMENT_RECOVERY_FROM_HOURS = 1
MOMENT_RECOVERY_TO_HOURS = 6
MOMENT_RECOVERY_SHARE_MIN = 0.75
# База ниже — слабая скважина, где и сам порог R2 ненадёжен (MIN_BASE_MOMENT
# в config.py R2): цепочка VMB_1221 с базой 38–47 восстанавливалась на 52–71 %.
MOMENT_BASE_MIN = 50.0
# Минимум отсчётов (СДМО пишет ~раз в 2 мин): база — ~2 ч работы, окно — ~1 ч
# из 5. Меньше — станция была без связи, по моменту не решаем.
MOMENT_BASE_MIN_SAMPLES = 60
MOMENT_WINDOW_MIN_SAMPLES = 30

# --- Нефть (ЦИТС, telemetry_well.qm_oil, т/сут) ---
# Годный замер: нефти не меньше этой доли нормы.
OIL_SHARE_MIN = 0.5
# Норма = max(техрежим по нефти на дату T0, медиана замеров за столько суток до T0).
OIL_NORM_LOOKBACK_DAYS = 14

# --- ABAI ---
# Статусы «скважина работает».
ABAI_WORK_STATUS_CODES = frozenset({"WRK", "PEXP"})
# Статусы, которые сами по себе означают отказ.
ABAI_FAILURE_STATUS_CODES = frozenset({"NINF", "ADEN"})
# Причины простоя, означающие отказ (подстрока, без регистра). Отключения
# электроэнергии, исследования, ППР и порывы коллектора сюда не входят.
ABAI_FAILURE_REASON_PATTERNS = (
    "подач",  # «Нет подачи», «Отсутствие подачи», «Снижение подачи»
    "прс",  # ПРС, ОПРС (ожидание ПРС)
    "крс",
    "заклин",
    "обрыв",
    "отворот",
    "авари",
    "прихват",
    "смена насос",
    "смена штанг",
)
# Время статусов ABAI в нашей копии — местное, не UTC. Сверено на проде 07.10.2026
# по 600 «отключениям электроэнергии» (сен 2026): станции СДМО пропадают со связи
# ровно в начале статуса (сдвиг 0 ч, не +5 ч), привод запускается к его концу.
# Так же местное время у ремонтов ABAI (начало ПРС-статуса = начало ремонта).
ABAI_STATUS_TIME_IS_UTC = False

