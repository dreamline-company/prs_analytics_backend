# Правила, которые считаются не по всем НГДУ: по остальным ведомости нет.
SHEET_NGDU_ABAI_IDS: dict[str, tuple[int, ...]] = {
    "R10": tuple(int(ngdu) for ngdu in R10_NGDUS),
}


def sheet_applies(detector_code: str, abai_ngdu_id: int) -> bool:
    """Считается ли правило по НГДУ: иначе пустая ведомость вводила бы в заблуждение."""
    ngdus = SHEET_NGDU_ABAI_IDS.get(detector_code)
    return ngdus is None or abai_ngdu_id in ngdus


