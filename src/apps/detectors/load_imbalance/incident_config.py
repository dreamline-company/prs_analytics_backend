"""Пороги жизненного цикла эпизода R9 (warning / alarm / нормализация).

`config.py` описывает само правило — что считается сработкой на одних сутках.
Здесь надстройка: когда сработка становится инцидентом, когда повышается
уровень и когда инцидент закрывается.

Нормализации в скриптах нет вообще: там эпизод просто кончается, когда
кончились alert-сутки, а кластеризация склеивает разрывы до 3 суток
(`CLUSTER_GAP_D`). Для живой системы этого мало — нужен явный гистерезис,
иначе инцидент закроется на первых же сутках без сработки, включая те, где
скважина просто не набрала снимков.
"""

# --- Сигнал правила (reason_code эпизодов) ---
# Наблюдение, а не диагноз: под одной сработкой в реестре ТР4-1 лежат и утечка
# клапанов, и неполное заполнение, и износ пары плунжер–цилиндр. R9 отвечает
# «идти смотреть эту скважину?», а не «что везти в ремонт».
REASON_LOAD_IMBALANCE = "load_imbalance"

# --- Уровень ---
# Первые alert-сутки — warning, вторые — alarm. Ровно как в скрипте:
# кластер из одних суток жёлтый, из двух и более — красный.
ALARM_ALERT_DAYS = 2

# --- Нормализация (гистерезис закрытия) ---
# Чистые сутки — это K ниже порога ДЕГРАДАЦИИ (config.K_DEGRADE), а не ниже
# алармного. Закрытие по алармному порогу дало бы флаппинг у границы:
# 0.21 → аларм, 0.19 → закрыт, 0.22 → новый инцидент, каждый день новый эпизод.
# Тот же порог автор использует для проверки восстановления после ремонта.
#
# Сколько подряд чистых суток нужно: не меньше разрыва, который скрипт ещё
# считает одним эпизодом (3 суток). Закроемся раньше — порежем на куски то, что
# валидированная логика считает одним событием, и метрики поедут относительно
# отчёта.
RECOVER_SUSTAIN_DAYS = 4

# Нет валидных суток столько подряд — закрываем как stale (станция снята, идёт
# ПРС, канал умер). Без этого инцидент висит вечно: отсутствие данных не даёт
# ни сработки, ни восстановления.
STALE_DAYS = 14

# Сколько суток-улик класть в payload вокруг события.
EVIDENCE_DAYS = 10
