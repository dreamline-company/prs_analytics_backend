"""Пороги и параметры правила R9 — перекос нагрузки на ходе ШГН.

Значения перенесены из скриптов форвард-прогона (`forward_runner.py`,
`r9_batch.py`) без подгонки: относительная ветвь откалибрована автором правила
на ~6300 плацебо скважино-днях здорового фонда, и трогать её отдельно от
повторной калибровки нельзя.

Правило считает по одному сигналу — моменту на валу (регистр 1991). Регистр
скорости (1998) в формулу НЕ входит и работает воротами «привод качает»:
снимки при остановленном станке в перцентили не попадают, иначе простои тянут
распределение к нулю и K начинает мерить простои, а не насос.
"""

# Версия набора порогов — пишется в инцидент для воспроизводимости.
CONFIG_VERSION = "r9-v1"

# --- Регистры источника ---
MOMENT_REGISTER = "1991"  # «Момент на валу», приведён к кривошипу, фунт-футы
SPEED_REGISTER = "1998"  # «Скорость», ворота «привод работает»

# --- Целевой флот детектора — ШГН ---
TARGET_TYPE_1900 = 1

# --- Разворот uint16 ---
# 1991 едет по Modbus беззнаковым 16-битным целым: отрицательный (генераторный)
# момент приезжает дополнительным кодом, −900 → 65536 − 900 = 64636. Без
# разворота P5 никогда не станет отрицательным (все отрицательные значения
# уехали в верх распределения), а P95 раздувается до ~64000 — K вырождается и
# правило не срабатывает ни разу.
WRAP_LIMIT = 32767.0
WRAP_PERIOD = 65536.0

# --- Перцентили внутри суток ---
# 95/5, а не min/max: min/max определяются одним снимком из сотен, и одной
# помехи опроса хватает, чтобы испортить сутки. За планкой P95 лежат ~5%
# снимков — чтобы сдвинуть её, нужен десяток согласованных значений, то есть
# реальный режим работы, а не помеха.
P_REVERSE = 0.05  # P5 — характерный обратный пик (ход вниз, генераторный)
P_MEDIAN = 0.5  # P50 — уровень нагрузки; в правило не входит, идёт в payload
P_WORKING = 0.95  # P95 — характерный рабочий пик (ход вверх)

# Сутки валидны от этого числа снимков при работающем приводе.
DAY_MIN_SAMPLES = 100

# --- Фон: скользящая база самой скважины ---
BASE_WINDOW_DAYS = 60
MIN_BASE_DAYS = 10
# Порог относительной ветви строится от P90 фоновых K — типичный высокий, но
# не экстремальный фон.
BASE_K_PERCENTILE = 0.9

# --- Три ветви ---
# Абсолютная: универсальная граница «так здоровые не работают». У здоровой
# уравновешенной скважины K держится в районе 0.02–0.08.
K_ALERT = 0.20
# Зона деградации: ниже неё сутки считаются здоровыми (в т.ч. для закрытия
# инцидента), выше — уже не норма, даже если до тревоги не дотянуло.
K_DEGRADE = 0.13
# Подавитель абсолютной ветви: у части фонда фон высок хронически
# (неуравновешенность станка), и для них 0.2 — обычная жизнь. Если собственный
# фоновый P90 выше этого, абсолютная ветвь на скважине глушится.
BASE_P90_LIMIT = 0.13
# Относительная ветвь: деградация против собственной нормы.
REL_FACTOR = 1.5
# Полная потеря нагрузки: P95 упал ниже этой доли фоновой медианы P95. Здесь K
# вырождается (знаменатель исчезает), диагноз ставится по факту — привод крутит
# практически пустой станок.
LOAD_LOSS_FRAC = 0.10

# --- Глубина первого прогона по станции ---
HISTORY_DAYS = 90
